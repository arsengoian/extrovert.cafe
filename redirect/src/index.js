// r.extrovert.cafe/<токен> → 302 на застосунок.
//
// Воркер навмисно нічого не рахує сам. Зарахування репоста вимагає знати,
// хто перейшов: власний перехід не має давати монет (api/src/routes/repost.js).
// Це знає лише сам застосунок, у якого є токен гравця, — а воркер бачить
// тільки IP. Тому тут чистий редирект, а клік рахує сторінка /r/<токен>.
//
// Що це дає: коротке посилання, яке не залежить від збірки застосунку, і
// справжній 302 — без JavaScript і без білого екрана на секунду.
const HOME = "/";

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const app = env.APP_ORIGIN ?? "https://extrovert.cafe";

    // Токен — перший сегмент шляху. Порожній шлях означає, що хтось
    // відкрив домен руками: ведемо на головну, а не показуємо помилку.
    const token = url.pathname.split("/").filter(Boolean)[0];
    if (!token) return Response.redirect(app + HOME, 302);

    // Дозволяємо лише те, що видає api: букви, цифри, дефіс, підкреслення
    // й кирилицю з нікнейма. Усе інше — спроба підсунути свій шлях.
    if (!/^[\p{L}\p{N}_-]{1,64}$/u.test(token)) return Response.redirect(app + HOME, 302);

    const target = `${app}/r/${encodeURIComponent(token)}${url.search}`;

    // 302, а не 301: куди веде посилання, ми ще можемо захотіти змінити, а
    // 301 браузери кешують назавжди.
    return new Response(null, {
      status: 302,
      headers: {
        location: target,
        // Короткий кеш: посилання живе довго, але поведінку хочемо мати
        // змогу поміняти того ж дня.
        "cache-control": "public, max-age=300",
        // Реферер до застосунку не передаємо: у ньому був би нікнейм того,
        // хто поділився.
        "referrer-policy": "no-referrer",
      },
    });
  },
};
