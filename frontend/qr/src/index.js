// qr.extrovert.cafe → 302 на застосунок, query як є.
//
// Адреса надрукована на наклейках (qr.extrovert.cafe?p=1, docs/urls.md) і не
// зміниться ніколи, а куди вона веде — міняємо будь-коли. Тому тут немає
// нічого, крім переадресації: жодної логіки, яку довелось би тримати
// сумісною з уже надрукованим. Точку з p забирає сам застосунок.
export default {
  fetch(request, env) {
    const url = new URL(request.url);
    const app = env.APP_ORIGIN ?? "https://extrovert.cafe";

    // Шлях відкидаємо: на наклейці його немає, і qr.* не має ставати другим
    // входом у маршрути застосунку. Query лишаємо цілком — інакше
    // загубиться p.
    return new Response(null, {
      status: 302,
      headers: {
        location: `${app}/${url.search}`,
        // 302 і без кешу: постійна тут адреса на наклейці, а не ціль. 301
        // чи закешований 302 телефон пам'ятав би й після зміни цілі.
        "cache-control": "no-store",
      },
    });
  },
};
