// Зупинка сервіса на сигнал.
//
// Потрібна не для краси. Під час деплою докер надсилає контейнеру SIGTERM і
// чекає `stop_grace_period`; хто сигнал не обробляє, того на 10-й секунді
// вбиває SIGKILL — посеред запиту, посеред транзакції, з невзятим із черги
// повідомленням. Нова версія при цьому вже приймає трафік, тобто втрата
// припадає рівно на момент, коли на неї найменше чекають.
//
// Порядок кроків має значення: спершу перестати приймати нове (http-сервер,
// петлі робіт), потім закрити те, через що доробляється поточне (Redis,
// пул Postgres). Тому steps — об'єкт, а не набір колбеків: у JS порядок
// ключів збережений, і в коді сервісу видно, що за чим гаситься.
export function onShutdown(steps, { log, timeoutMs = 25_000 } = {}) {
  let started = false;

  const stop = async (signal) => {
    // Другий сигнал нічого не прискорює, лише плутає крок посеред роботи.
    if (started) return;
    started = true;
    log?.info?.(`${signal}: зупиняємось`);

    // Жорсткий дедлайн. Якщо якийсь крок завис (redis не відповідає,
    // запит у польоті не завершується), контейнер має піти сам і вчасно —
    // інакше на нього чекає той самий SIGKILL, тільки пізніше.
    const hard = setTimeout(() => {
      log?.error?.("зупинка не вклалася у відведений час, виходимо різко");
      process.exit(1);
    }, timeoutMs);
    hard.unref?.();

    for (const [name, step] of Object.entries(steps)) {
      try {
        await step();
      } catch (e) {
        // Помилка на одному кроці не має спиняти решту: пул треба закрити
        // навіть тоді, коли http-сервер закрився погано.
        log?.error?.(`крок зупинки «${name}» не вдався`, e);
      }
    }

    clearTimeout(hard);
    log?.info?.("зупинились");
    process.exit(0);
  };

  process.on("SIGTERM", () => stop("SIGTERM"));
  process.on("SIGINT", () => stop("SIGINT"));
}
