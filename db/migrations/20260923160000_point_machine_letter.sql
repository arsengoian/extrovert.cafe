-- Літера машини в точці (відповіді власника 23.09.2026).
--
-- Оператор автомата нумерує позиції з літери машини: перша — «a», друга —
-- «b», і так далі, а номер позиції на всіх машинах однаковий (024 — це
-- завжди какао). Точка = одна машина, завжди; каса теж по одній на машину.
--
-- Тому код для Checkbox і Jetinno збирається як `літера + номер`, і
-- літеру треба знати саме на точці. Сама таблиця `drinks` лишається
-- спільною: номери в машин збігаються.
--
-- Поки машина одна, у всіх точок «a» — але зашивати її в код не можна:
-- рівно так у нас уже з'явились вигадані коди з «x».

-- migrate:up
alter table points add column machine_letter text not null default 'a'
    check (machine_letter ~ '^[a-z]$');

comment on column points.machine_letter is
    'Літера машини для кодів Checkbox/Jetinno: код позиції = літера + номер';

-- migrate:down
alter table points drop column machine_letter;
