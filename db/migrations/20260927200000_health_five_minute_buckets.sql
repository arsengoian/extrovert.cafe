-- Overseer пише відра здоров'я по 5 хвилин замість 30 (27.09.2026), а
-- адмінка на коротких періодах (6 годин, доба) малює саме п'ятихвилинні
-- клітинки. Старий півгодинний рядок потрапив би лише в одну з шести, а
-- решта стояли б сірими — наче даних не було, хоча вони є (власник:
-- «щоб відображалося по моїх старих даних»).
--
-- Тож кожне старе відро розкладаємо на шість п'ятихвилинних із тим самим
-- станом. Зелене відро від цього не бреше: зеленими були всі проби за ці
-- пів години. Червоне займе всі шість клітинок — рівно так, як ці пів
-- години показувались і досі; в яку саме п'ятихвилинку падало, ми не
-- знаємо, і вигадувати цього не беремось.
--
-- Міграції котяться до перезапуску сервісів (docker/rollout.sh), тож на
-- цей момент у таблиці лише півгодинні рядки: хвилина 0 чи 30. Уже
-- наявних рядків не чіпаємо (on conflict do nothing).
insert into health_samples (target, bucket_start, ok, detail, samples, ms_total, ms_count)
select h.target, h.bucket_start + make_interval(mins => m), h.ok, h.detail, h.samples, h.ms_total, h.ms_count
  from health_samples h, generate_series(5, 25, 5) as m
 where extract(minute from h.bucket_start)::int in (0, 30)
   and extract(second from h.bucket_start) = 0
on conflict (target, bucket_start) do nothing;

