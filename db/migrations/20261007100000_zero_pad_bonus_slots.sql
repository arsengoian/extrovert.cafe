-- Фіскальний застосунок на терміналі будує код товару як «літера машини +
-- '0' + номер позиції» незалежно від довжини номера: Еспресо (33) →
-- «a033», Еспресо з молоком (102) → «a0102», Окріп (107) → «a0107».
-- Бонусні позиції завели без цього нуля («901»), тож їхній код виходив
-- «a901» і не збігався з тим, що шле автомат. Додаємо нуль, як у решти
-- (власник, 07.10.2026). Бонуси ще неактивні й не продавались, промо на
-- них немає, тож перейменування slot нічого не ламає.
update drinks set slot = '0' || slot where slot in ('901', '902', '903', '904');

