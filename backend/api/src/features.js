// Вимкнене зникає з обох боків. Застосунок отримує ці прапорці в GET /me
// (поле features) і не малює кнопок, а сервер на вимкнене відповідає
// 404 feature_off — купити повз інтерфейс, прямим запитом, теж не вийде.
// Перемкнув — задеплоїв api; клієнт підхопить на наступному /me, свого
// релізу йому не треба.
//
// Оплата, розпочата до вимкнення, усе одно зараховується: settle() у
// payments.js прапорців не дивиться, бо гроші вже пішли.
import { fail } from "./errors.js";

export const FEATURES = Object.freeze({
  // Продаж монет за гривні: пачки в «Поповнити», mono pay.
  coin_packs: true,
  // Щаслива скринька за гривні, mono pay. За монети вона продається завжди.
  crate_cash: false,
});

export function requireFeature(name) {
  if (!FEATURES[name]) fail(404, "feature_off");
}
