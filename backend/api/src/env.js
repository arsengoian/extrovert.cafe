// Чи дозволені девелоперські шляхи: вхід без пошти (/auth/dev,
// /admin/dev-login), «оплата» без mono, роути /dev/*, посилання для входу в
// лозі замість листа.
//
// Дві незалежні умови, і обидві мають сказати «не прод». Образ сервіса сам
// ставить NODE_ENV=production (docker/bun.Dockerfile), а .env сервера —
// APP_ENV=production, тож помилка в одному місці нічого не відкриває.
// Раніше тут був ще DEV_TOOLS=1, який умикав усе це й у проді: один рядок,
// перенесений у серверний .env із локального, — і будь-хто входив би в
// будь-який нікнейм. Такого перемикача більше немає.
export const DEV = process.env.NODE_ENV !== "production" && process.env.APP_ENV !== "production";

// Прод — усе, що не DEV. Окремою назвою там, де важливо протилежне:
// відмовитись стартувати без ключа, не пустити localhost у CORS.
export const PROD = !DEV;
