// Сторінки списків адмінки (власник, 16.10.2026): n записів на сторінку й
// перехід між ними, а не «перші 200» чи «останні 50». Досі кожен список
// обрізався своїм limit, і що лежало за ним, з адмінки видно не було взагалі;
// а там, де KPI рахувався з того самого обрізаного списку («Сегментів» у
// відео — рівно 100), він ще й брехав.
//
// Сторінка — це limit/offset: списки тут — журнали, які гортають від свіжого,
// і далі кількох перших сторінок майже не ходять, тож keyset заради
// глибоких сторінок не потрібен. Загальну кількість рахує окремий count із
// тим самим where — інакше «сторінка 3 з ?» нічого не каже.

// pageOf(req.query, { per, max }) → { page, per, offset } — номер сторінки з
// одиниці; per обмежений max, щоб ?per=100000 не витягнув усю таблицю.
export function pageOf(query, { per: defPer = 50, max = 200 } = {}, prefix = "") {
  const num = (k) => Number.parseInt(query?.[`${prefix}${k}`] ?? "", 10);
  const per = Math.min(max, Math.max(1, num("per") || defPer));
  const page = Math.max(1, num("page") || 1);
  return { page, per, offset: (page - 1) * per };
}

// Те, що їде в адмінку поруч зі списком: компонент Pager (ui.jsx) з цього
// малює «1–50 з 734» і кнопки.
export const pageInfo = ({ page, per }, total) => ({ page, per, total: Number(total ?? 0) });
