/* ws.h — клієнт вебсокета подій для кіоска.
 *
 * Кіоск слухає канал своєї точки (`point:<id>`) і дізнається звідти, що
 * чек пробито й бонус можна забирати — той самий канал, що й у телефона,
 * тільки з іншим токеном (docs/services.md §4).
 *
 * Чому не libwebsockets. На малині Stretch, а там lws 2.0 із 2016 року й
 * іншим API, ніж усе, що є на сучасному десктопі; збирати той самий код
 * під дві несумісні версії бібліотеки — гарантія, що одна з двох збірок
 * тихо відстане. Тут натомість RFC 6455 поверх з'єднання, яке відкриває
 * libcurl (CURLOPT_CONNECT_ONLY): curl уже є в залежностях, він же тягне
 * TLS для wss, а кадри вебсокета — сотня рядків, які поводяться однаково
 * скрізь.
 *
 * Потік окремий, як у menu_poll: мережа не має права затримати кадр.
 * Головний цикл раз на кадр забирає готові події через ws_drain() — без
 * блокувань, без алокацій, без роботи з мережею на своєму боці.
 */
#ifndef POS_NATIVE_WS_H
#define POS_NATIVE_WS_H

#include <stdbool.h>

/* Подія bonus_ready із каналу точки. Поля рівно ті, що шле checkbox
 * (backend/checkbox/src/receipts.js): id потрібен для відкидання повторів —
 * доставка «принаймні раз», тож та сама подія може прийти двічі. */
typedef struct {
    long long id;             /* outbox.id */
    char event[32];           /* поки лише "bonus_ready" */
    char code[32];            /* system_code напою: ключ до меню кіоска */
    char drink[64];           /* назва — запасний варіант, коли коду немає в меню */
    int coins;
    char claim_token[64];     /* із нього кіоск робить QR */
    int expires_in_s;
    /* Скільки предметів випало разом із бонусом (плитка «секретний предмет»
     * у попапі). -1 — поля в події немає: checkbox його ще не шле
     * (receipts.js не заповнює bonus_grants.items), і тоді кіоск вгадує
     * з меню — bonus.c. Приймається число або масив (тоді — його довжина). */
    int items;
} ws_event_t;

/* Знімок стану точки: те, що кіоск питає після кожного (пере)підключення
 * (GET /points/<id>/state, docs/services.md §4). Pub/sub нічого не зберігає,
 * тож подія, опублікована в ті півсекунди, поки ми перепідключались, не
 * дійде ніколи — людина стоятиме з чеком перед екраном без QR. Знімок дає
 * повний список активних QR, і панель вирівнюється по ньому. */
#define WS_SNAPSHOT_MAX 8

typedef struct {
    int count;
    ws_event_t rows[WS_SNAPSHOT_MAX];  /* expires_in_s тут — ЛИШОК, а не повний TTL */
} ws_snapshot_t;

typedef struct ws_client ws_client_t;

/* Запускає фоновий потік. Повертає NULL лише якщо не вистачило памʼяті —
 * недоступний сервер не помилка запуску, а звичайний стан: клієнт
 * перепідключатиметься сам, поки його не зупинять.
 *
 * state_url — куди ходити по знімок після кожного підключення
 * (`<api>/points/<точка>/state`). Порожній рядок вимикає знімок: так
 * поводиться десктопна збірка без API_URL. */
ws_client_t *ws_start(const char *url, const char *token, const char *state_url);

/* Забирає до max подій у out, повертає скільки забрав. Викликати з
 * головного потоку раз на кадр. */
int ws_drain(ws_client_t *c, ws_event_t *out, int max);

/* Забирає знімок, якщо після минулого виклику приїхав новий. true — у out
 * лежить повний список активних QR точки; головний цикл вирівнює по ньому
 * панель: чого немає в списку — прибирає, чого бракує — додає. */
bool ws_take_snapshot(ws_client_t *c, ws_snapshot_t *out);

/* Чи є живе зʼєднання просто зараз — для індикатора й телеметрії. */
bool ws_online(ws_client_t *c);

void ws_stop(ws_client_t *c);

#endif
