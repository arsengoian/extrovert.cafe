/* qr.h — QR-код: білі модулі з rx=0.3 на прозорому фоні, рівно як у макеті
 * (design/monitor-menu/, qrcode-generator, ECC «M»). Прозорий фон навмисно:
 * код лягає в темне коло градієнтного кільця, а не на власну білу підкладку —
 * квадратна плашка під кодом виглядала б чужою на круглому бейджі.
 *
 * Єдине на екрані, що свідомо НЕ SVG. Спробували 21.09.2026: librsvg 2.40 на
 * Pi 1 малював 64-піксельний код 650 мс (<rect> на модуль) і 216 мс (один
 * <path> з дугами) — і стільки ж стояв кадр на кожному бонусі. Cairo малює
 * той самий контур одним заповненням за мілісекунди, тож код домальовується
 * поверх уже відрендереного SVG-рядка чи попапа.
 */
#ifndef POS_NATIVE_QR_H
#define POS_NATIVE_QR_H

#include <cairo/cairo.h>
#include <stdbool.h>

/* Малює код у квадрат (x, y, size) на cr. Тихої зони тут немає, її дає коло
 * кільця навколо (у макеті 64 px код у колі діаметром 104, 112 px — у 188).
 * false, якщо текст не влазить у жодну версію QR (за наших коротких URL шанс
 * малий, але кіоск не має впасти на битому payload) — тоді нічого не малює. */
bool qr_paint(cairo_t *cr, const char *text, double x, double y, double size);

#endif
