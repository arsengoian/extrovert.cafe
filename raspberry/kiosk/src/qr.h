/* qr.h — QR-код: білі заокруглені модулі на прозорому фоні. Прозорий фон
 * навмисно: код лягає поверх градієнтного кільця бонусу (bonus.c), а не
 * на власну білу підкладку — квадратна плашка під кодом виглядала б чужою
 * на круглому бейджі.
 */
#ifndef POS_NATIVE_QR_H
#define POS_NATIVE_QR_H

#include <cairo/cairo.h>

/* text — довільний рядок (URL бонусу). px_size — сторона квадрата, у який
 * вписується код РАЗОМ із тихою зоною (quiet zone), однакового розміру
 * незалежно від версії/кількості модулів даного тексту.
 * NULL, якщо текст не влазить у жодну версію QR (замалий шанс за наших
 * коротких URL, але перевіряти треба — кіоск не має впасти на битому
 * payload). */
cairo_surface_t *render_qr(const char *text, int px_size);

#endif
