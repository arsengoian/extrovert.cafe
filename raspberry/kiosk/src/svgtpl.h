/* svgtpl.h — рендер справжніх SVG-макетів (design/monitor-menu/, оригінали),
 * адаптованих у assets/templates/ — замість ручного відтворення Cairo-
 * викликами. Підхід від 29.08.2026: власник попросив компонувати цілий
 * SVG-рядок (текстова підстановка {{КЛЮЧ}} → значення) і віддавати його
 * librsvg одним шматком — для меню й реклами, які перемальовуються рідко
 * (раз на menu_poll). Рядки бонусів — окремо (bonus.c): фон теж шаблон,
 * але кільце прогресу рухається щосекунди й лишається прямим Cairo.
 *
 * Чому це закриває клас багів, який хендкодинг не закривав: librsvg сам
 * коректно трактує font-size="31" як 31 CSS-піксель (SVG-специфікація),
 * тоді як ручний Pango font_spec без "px" читав те саме число як пункти
 * при 96dpi — рівно та помилка, яку піймали 29.08.2026 на заголовку
 * реклами. Копіюючи реальну розмітку макета замість передруку координат
 * руками, цей клас розбіжностей зникає за конструкцією.
 */
#ifndef POS_NATIVE_SVGTPL_H
#define POS_NATIVE_SVGTPL_H

#include <cairo/cairo.h>

/* Читає файл шаблону цілком у новий malloc'аний рядок (з '\0').
 * NULL при помилці. */
char *svgtpl_load(const char *path);

/* {{KEY}} → value, послідовно для кожної пари keys[i]/values[i] (n пар).
 * Повертає НОВИЙ malloc'аний рядок; tpl не змінюється. Токен, якого
 * немає в шаблоні, просто ігнорується (не помилка) — так само як
 * невикористане поле JSON. NULL при помилці алокації. */
char *svgtpl_sub(const char *tpl, const char *const *keys, const char *const *values, int n);

/* Екранує &,<,>," для безпечної вставки як текстового вмісту/атрибута.
 * Новий malloc'аний рядок. Обов'язково для будь-якого динамічного тексту
 * (назва напою, рекламний копірайт) — інакше символ у даних ламає XML. */
char *svgtpl_esc(const char *s);

/* SVG сам нічого не ellipsize'ить і не обрізає overflow — саме це дало
 * баг заголовка реклами 29.08.2026 (clip-path панелі різав слово навпіл).
 * Вимірює text ТИМ САМИМ Pango-стеком, яким librsvg рендерить (тому
 * узгоджено з тим, що покаже сама SVG), і якщо не влазить у max_w при
 * font_spec (формат "Родина розмірpx", як usual) — вкорочує по цілих
 * UTF-8-кодпоінтах і дописує "…". Повертає НОВИЙ malloc'аний рядок
 * (навіть якщо текст і так влазив — просто копію), готовий вставляти в
 * {{NAME}} без подальшого екранування html-небезпечних символів САМ ПО
 * СОБІ (виклич svgtpl_esc() окремо, це різні турботи). */
char *svgtpl_ellipsize(const char *text, const char *font_spec, double max_w);

/* Рендерить ГОТОВИЙ (уже підставлений) SVG-рядок у Cairo-поверхню
 * розміром w×h. base_dir — базовий каталог для відносних href усередині
 * SVG (assets/...): встановлюється як base URI перед парсингом, тому
 * шаблони можуть посилатись на "drinks/espresso.png" відносно assets/,
 * а не тягнути повний шлях у кожен {{IMG}}. NULL при помилці парсингу. */
cairo_surface_t *svgtpl_render(const char *svg_text, int w, int h, const char *base_dir);

#endif
